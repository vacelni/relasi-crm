import type { AiSource } from '@/lib/ai/types';

/** Says which engine produced an AI result, and how many calls are left today. */
export function AiSourceNote({ source, remaining }: { source: AiSource; remaining?: number | null }) {
  return (
    <p className="text-xs text-muted">
      {source === 'claude' ? 'Generated by Claude Haiku. Check before relying on it.' : 'Heuristic result: no AI key is configured on this server.'}
      {remaining != null ? ` ${remaining} AI calls left today.` : ''}
    </p>
  );
}
